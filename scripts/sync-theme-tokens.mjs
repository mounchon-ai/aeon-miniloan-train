// Generates apps/web/app/theme.tokens.css from .aeon/mockup/theme.json.
//
// theme.json is the ONE source of colour, spacing and type for this project (imported by
// /mock:theme from the signed design-system handoff). The web app cannot @import across
// ../../../.aeon/ because docker-compose builds apps/web with `context: ../apps/web` — anything
// outside that directory is not in the build context. So the tokens are generated INTO the app and
// committed, and this script is re-run whenever /mock:sync brings a new theme in.
//
// Run from the repo root: node scripts/sync-theme-tokens.mjs
import { readFileSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";

const SRC = ".aeon/mockup/theme.json";
const OUT = "apps/web/app/theme.tokens.css";

const theme = JSON.parse(readFileSync(SRC, "utf8"));
const light = theme.tokens?.light ?? {};
const dark = theme.tokens?.dark ?? {};
if (!Object.keys(light).length) {
  console.error(`${SRC} carries no tokens.light — nothing to generate`);
  process.exit(1);
}

const decls = (set, indent) =>
  Object.entries(set)
    .map(([name, t]) => `${indent}${name}: ${typeof t === "string" ? t : t.value};`)
    .join("\n");

const css = `/* GENERATED by scripts/sync-theme-tokens.mjs from ${SRC} — do not edit by hand.
   Re-run the script after /mock:theme or /mock:sync changes the theme. */

:root {
${decls(light, "  ")}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${decls(dark, "    ")}
  }
}

:root[data-theme="dark"] {
${decls(dark, "  ")}
}
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, css);
console.log(`${OUT} — ${Object.keys(light).length} light token(s) · ${Object.keys(dark).length} dark override(s)`);
